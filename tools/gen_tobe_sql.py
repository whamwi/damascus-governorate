#!/usr/bin/env python3
"""Generate the load for a proposed (TO-BE) structure from its reviewed mapping.

    python3 tools/gen_tobe_sql.py analysis/2026-10-28_tobe_3_1_map.csv DG_TOBE_3_1 \
        'الهيكلية المقترحة 3.1' apex/data/2026-10-28_tobe_3_1.sql

The mapping CSV is maintained by hand (one row per proposed unit, or per
current unit not placed) and is the only input; nothing is matched here.

The scenario is a clone of DG_ASIS_CARDS with the proposal applied at the
levels the proposal describes (governor, sector deputies, directorates):
  new       a sector or directorate, with a placeholder head (no card)
  same / renamed / split
            the current directorate moves under its sector, takes the
            proposed name (and code), and keeps its sub-units and positions
  merged    the first source is kept as above; the others hand it their
            sub-units and positions, and their heads report to its head
  abolished the current unit and everything under it is left out
Sub-units and positions that came across from the current structure keep
their source (CARDS); only what the proposal itself states is PROPOSAL.
Every row is also written to ORG_UNIT_LINEAGE, which the comparison page
reads; rows of LOW confidence are the open questions (IS_OPEN = 'Y').
The file is rerunnable: it drops the scenario and builds it again.
"""
import csv, sys

src_csv, code, name_ar, out = sys.argv[1:5]
rows = list(csv.DictReader(open(src_csv, encoding='utf-8')))


def q(s):
    return 'NULL' if s is None or s == '' else "'" + str(s).replace("'", "''") + "'"


def parent_of(r):
    s = r['sector']
    return 'U-GOV' if s in ('', 'CENTRAL', '?') else s


def target_code(r):
    # the governor keeps its code in every scenario; the rest take the proposed one
    return 'U-GOV' if r['tobe_code'] == 'T-GOV' else r['tobe_code']


sectors = [r for r in rows if r['tobe_code'].startswith('T-S-')]
placed = [r for r in rows if r['tobe_code'] and r['tobe_code'] != 'T-GOV' and r not in sectors]
abolished = [r for r in rows if r['relation'] == 'abolished']
assert all(r['relation'] in ('same', 'renamed', 'merged', 'split', 'new', 'abolished') for r in rows)
assert all((r['relation'] == 'new') == (r['asis_codes'] == '') for r in rows if r['tobe_code'] != 'T-GOV')

s = [f'''-- {name_ar} ({code}): generated by tools/gen_tobe_sql.py from {src_csv}; do not edit by hand
-- {len(sectors)} sectors, {len(placed)} directorates, {len(abolished)} current units not placed

DECLARE
  l_src  NUMBER;
  l_new  NUMBER;
  l_n    NUMBER;

  -- local subprograms cannot be called from SQL: every id is read into a variable first
  FUNCTION uid_of (p_code VARCHAR2) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT unit_id INTO l FROM org_unit WHERE scenario_id = l_new AND unit_code = p_code;
    RETURN l;
  END;

  FUNCTION head_of (p_code VARCHAR2) RETURN NUMBER IS
    l_u NUMBER := uid_of(p_code);
    l   NUMBER;
  BEGIN
    SELECT MIN(position_id) INTO l FROM org_position
     WHERE scenario_id = l_new AND unit_id = l_u AND heads_unit = 'Y';
    RETURN l;
  END;

  PROCEDURE add_unit (p_code VARCHAR2, p_parent VARCHAR2, p_type VARCHAR2, p_name VARCHAR2,
                      p_head VARCHAR2, p_sort NUMBER) IS
    l_parent NUMBER := uid_of(p_parent);
    l_rep    NUMBER := head_of(p_parent);
    l_unit   NUMBER;
  BEGIN
    INSERT INTO org_unit (scenario_id, unit_code, parent_unit_id, unit_type_code, name_ar,
                          source_type_code, source_ref, sort_order)
    VALUES (l_new, p_code, l_parent, p_type, p_name, 'PROPOSAL', '{name_ar}', p_sort)
    RETURNING unit_id INTO l_unit;
    -- a head with no card yet: a placeholder, as for the units the cards name without a head
    INSERT INTO org_position (scenario_id, position_code, unit_id, title_ar, reports_to_pos_id, heads_unit,
                              is_placeholder, link_method_code, source_type_code, sort_order)
    VALUES (l_new, 'P-' || p_code, l_unit, p_head, l_rep, 'Y', 'Y', 'PROPOSAL', 'PROPOSAL', 0);
  END;

  -- a current unit placed in the proposal: moved, renamed, its head re-pointed
  PROCEDURE place (p_from VARCHAR2, p_code VARCHAR2, p_parent VARCHAR2, p_name VARCHAR2, p_sort NUMBER) IS
    l_parent NUMBER := uid_of(p_parent);
    l_rep    NUMBER := head_of(p_parent);
    l_head   NUMBER;
    l_unit   NUMBER;
  BEGIN
    UPDATE org_unit
       SET unit_code = p_code, parent_unit_id = l_parent, unit_type_code = 'DIRECTORATE',
           name_ar = p_name, source_type_code = 'PROPOSAL', source_ref = '{name_ar}', sort_order = p_sort,
           notes = 'ما تحت المديرية منقول من الهيكل القائم كما تصفه البطاقات؛ المقترح لا يتناوله'
     WHERE scenario_id = l_new AND unit_code = p_from
    RETURNING unit_id INTO l_unit;
    l_head := head_of(p_code);
    IF l_head IS NULL THEN
      INSERT INTO org_position (scenario_id, position_code, unit_id, title_ar, reports_to_pos_id, heads_unit,
                                is_placeholder, link_method_code, source_type_code, sort_order)
      VALUES (l_new, 'P-' || p_code, l_unit, 'رئيس ' || p_name, l_rep, 'Y', 'Y', 'PROPOSAL', 'PROPOSAL', 0);
    ELSE
      UPDATE org_position SET reports_to_pos_id = l_rep, link_method_code = 'PROPOSAL'
       WHERE position_id = l_head;
    END IF;
  END;

  -- a second current unit merged into a placed one: its people and sub-units move in
  PROCEDURE merge_into (p_from VARCHAR2, p_into VARCHAR2) IS
    l_from NUMBER := uid_of(p_from);
    l_into NUMBER := uid_of(p_into);
    l_rep  NUMBER := head_of(p_into);
  BEGIN
    UPDATE org_position SET reports_to_pos_id = l_rep, link_method_code = 'PROPOSAL', heads_unit = 'N'
     WHERE scenario_id = l_new AND unit_id = l_from AND heads_unit = 'Y';
    UPDATE org_position SET unit_id = l_into WHERE scenario_id = l_new AND unit_id = l_from;
    UPDATE org_unit SET parent_unit_id = l_into WHERE scenario_id = l_new AND parent_unit_id = l_from;
    DELETE FROM org_unit WHERE unit_id = l_from;
  END;

  -- a current unit not placed: it and everything under it are left out
  -- (already gone when an abolished unit above it was left out first)
  PROCEDURE leave_out (p_code VARCHAR2) IS
    l_root NUMBER;
  BEGIN
    SELECT MIN(unit_id) INTO l_root FROM org_unit WHERE scenario_id = l_new AND unit_code = p_code;
    IF l_root IS NULL THEN RETURN; END IF;
    DELETE FROM org_unit_tmp_ids;
    INSERT INTO org_unit_tmp_ids
    SELECT unit_id FROM org_unit WHERE scenario_id = l_new
     START WITH unit_id = l_root CONNECT BY PRIOR unit_id = parent_unit_id;
    SELECT COUNT(*) INTO l_n FROM org_position o
     WHERE o.scenario_id = l_new AND o.unit_id NOT IN (SELECT id FROM org_unit_tmp_ids)
       AND o.reports_to_pos_id IN (SELECT position_id FROM org_position
                                    WHERE unit_id IN (SELECT id FROM org_unit_tmp_ids));
    IF l_n > 0 THEN
      raise_application_error(-20001, p_code || ': ' || l_n || ' positions outside it report into it');
    END IF;
    UPDATE org_position SET reports_to_pos_id = NULL
     WHERE scenario_id = l_new AND unit_id IN (SELECT id FROM org_unit_tmp_ids);
    DELETE FROM org_position WHERE scenario_id = l_new AND unit_id IN (SELECT id FROM org_unit_tmp_ids);
    UPDATE org_unit SET parent_unit_id = NULL WHERE unit_id IN (SELECT id FROM org_unit_tmp_ids);
    DELETE FROM org_unit WHERE unit_id IN (SELECT id FROM org_unit_tmp_ids);
  END;

BEGIN
  SELECT scenario_id INTO l_src FROM org_scenario WHERE scenario_code = 'DG_ASIS_CARDS';

  FOR o IN (SELECT scenario_id FROM org_scenario WHERE scenario_code = {q(code)}) LOOP
    UPDATE org_position SET reports_to_pos_id = NULL WHERE scenario_id = o.scenario_id;
    DELETE FROM org_position WHERE scenario_id = o.scenario_id;
    UPDATE org_unit SET parent_unit_id = NULL WHERE scenario_id = o.scenario_id;
    DELETE FROM org_unit WHERE scenario_id = o.scenario_id;
    DELETE FROM org_unit_lineage WHERE scenario_id = o.scenario_id;
    DELETE FROM org_scenario WHERE scenario_id = o.scenario_id;
  END LOOP;

  l_new := org_scenario_pkg.clone_scenario(l_src, {q(code)}, {q(name_ar)}, 'TO_BE');
  UPDATE org_scenario
     SET description = 'هيكلية محافظة دمشق 3.1 (عرض المحافظة): المحافظ، المكاتب المركزية، ستة قطاعات بمعاونين، '
                    || 'والمديريات. ما تحت المديريات منقول من الهيكل القائم كما تصفه البطاقات.',
         legal_basis = NULL
   WHERE scenario_id = l_new;
''']

s.append('  -- sector deputies, under the governor')
for i, r in enumerate(sectors, 1):
    s.append(f"  add_unit({q(r['tobe_code'])}, 'U-GOV', 'SECTOR', {q(r['tobe_name'])}, {q(r['tobe_name'])}, {i * 10});")

s.append('\n  -- directorates, in the order of the mapping')
merges = []
for i, r in enumerate(placed, 1):
    srcs = [c for c in r['asis_codes'].split('|') if c]
    if r['relation'] == 'new':
        s.append(f"  add_unit({q(r['tobe_code'])}, {q(parent_of(r))}, 'DIRECTORATE', {q(r['tobe_name'])}, "
                 f"{q('مدير ' + r['tobe_name'])}, {i * 10});")
    else:
        s.append(f"  place({q(srcs[0])}, {q(target_code(r))}, {q(parent_of(r))}, {q(r['tobe_name'])}, {i * 10});")
        merges += [(c, target_code(r)) for c in srcs[1:]]

s.append('\n  -- second sources of a merge')
for c, into in merges:
    s.append(f"  merge_into({q(c)}, {q(into)});")

s.append('\n  -- أمين السر stays, in مكتب المحافظ (slide 1); the level he headed does not')
s.append("  DECLARE\n    l_to NUMBER := uid_of('U-18'); l_rep NUMBER := head_of('U-18'); l_from NUMBER := uid_of('U-16');\n"
         "  BEGIN\n    UPDATE org_position SET unit_id = l_to, heads_unit = 'N', reports_to_pos_id = l_rep,\n"
         "           link_method_code = 'PROPOSAL'\n     WHERE scenario_id = l_new AND unit_id = l_from;\n  END;")
s.append('\n  -- current units not placed')
for r in abolished:
    for c in r['asis_codes'].split('|'):
        s.append(f"  leave_out({q(c)});")

s.append('\n  -- lineage: what the comparison page reads')
for r in rows:
    srcs = [c for c in r['asis_codes'].split('|') if c] or [None]
    for c in srcs:
        unit = None if r['relation'] == 'abolished' else target_code(r)
        s.append('  INSERT INTO org_unit_lineage (scenario_id, unit_code, source_scenario_id, source_unit_code, '
                 'relation, confidence, is_open, sector_code, note)\n'
                 f"  VALUES (l_new, {q(unit)}, l_src, {q(c)}, {q(r['relation'].upper())}, {q(r['confidence'].upper())}, "
                 f"{q('Y' if r['confidence'] == 'low' else 'N')}, {q(r['sector'])}, {q(r.get('note_ar') or r['note'])});")
s.append('END;\n/\n')

open(out, 'w', encoding='utf-8').write('\n'.join(s) + '\nCOMMIT;\n')
print(f'{out}: {len(sectors)} sectors, {len(placed)} directorates ({len(merges)} merged sources), '
      f'{len(abolished)} not placed, {sum(len([c for c in r["asis_codes"].split("|") if c] or [1]) for r in rows)} lineage rows')
