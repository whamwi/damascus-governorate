"""Generate the SQL that loads one batch into the DG schema.

    python3 tools/gen_load_sql.py analysis/2026-10-27_hierarchy.json analysis/unit_map.csv \
        "incoming/2026-10-27/OneDrive_1_10-27-2026/توزيع العاملين.xlsx" 2026-10-27 apex/data

Writes apex/data/<batch>_NN_*.sql, run in file order. Every statement is a small
anonymous block (under ~16 KB), so the files run the same way in SQLcl, in APEX
SQL Workshop > SQL Scripts, or block by block over ORDS.

Codes are deterministic, so reloading the same batch updates rows in place:
    U-GOV, U-16, U-18, U-18-02, U-18-02-01   units, by article then order of first appearance
    JD-18-003                                card 3 of article 18, in file order
    P-18-003 / P-18-X01                      the position for that card / a placeholder head
"""
import csv, json, re, sys, pathlib, collections
import openpyxl

src, map_csv, staff_xlsx, batch, outdir = sys.argv[1:6]
outdir = pathlib.Path(outdir); outdir.mkdir(parents=True, exist_ok=True)
D = json.load(open(src, encoding='utf-8'))
umap = list(csv.DictReader(open(map_csv, encoding='utf-8')))
SCEN = 'DG_ASIS_CARDS'
MAX = 16000


def q(s):
    if s is None or s == '': return 'NULL'
    return "'" + str(s).replace("'", "''") + "'"


def write(name, header, stmts):
    """Pack statements into anonymous blocks of at most MAX characters."""
    blocks, cur = [], []
    for s in stmts:
        if cur and sum(map(len, cur)) + len(s) > MAX:
            blocks.append(cur); cur = []
        cur.append(s)
    if cur: blocks.append(cur)
    body = [f'-- {header}\n-- generated by tools/gen_load_sql.py from batch {batch}; do not edit by hand\n'
            f'-- {len(stmts)} statements in {len(blocks)} blocks\n']
    for b in blocks:
        body.append("DECLARE\n  l_s NUMBER;\n  l_b NUMBER;\nBEGIN\n"
                    f"  SELECT scenario_id INTO l_s FROM org_scenario WHERE scenario_code = '{SCEN}';\n"
                    f"  SELECT batch_id INTO l_b FROM dg_batch WHERE batch_code = '{batch}';\n"
                    + ''.join('  ' + s.replace('\n', '\n  ') + '\n' for s in b) + "  COMMIT;\nEND;\n/\n")
    (outdir / f'{batch}_{name}.sql').write_text('\n'.join(body), encoding='utf-8')
    print(f'{name}: {len(stmts)} statements, {len(blocks)} blocks')


# ---- normalisation, the same rules as the register ---------------------------------
def cls(s):
    s = s or ''
    if 'عليا' in s: return 'TOP_MGMT'
    if 'وسط' in s: return 'MID_MGMT'
    if re.search(r'^[اإ]د(ا|ر)', s): return 'ADMIN'
    if 'فني' in s: return 'TECHNICAL'
    if re.search('خدم|عضل', s): return 'SERVICE'
    return 'UNSPECIFIED'

def qual(s):
    for k, w in [('POSTGRAD', 'ماجستير|دكتوراه|دراسات عليا'), ('UNIVERSITY', 'جامع|هندس|إجازة|اجازة'),
                 ('MILITARY', 'عسكري|شرطة'), ('INSTITUTE', 'معهد'), ('SECONDARY', 'ثانوي'),
                 ('PREPARATORY', 'اعدادي|إعدادي'), ('PRIMARY', 'ابتدائ|محو')]:
        if re.search(w, s or ''): return k
    return 'UNSPECIFIED'

def effort(s):
    s = s or ''
    mental, phys = 'فكري' in s, bool(re.search('جسدي|عضلي', s))
    return 'MIXED' if mental and phys else 'MENTAL' if mental else 'PHYSICAL' if phys else 'UNSPECIFIED'

def years(s):
    m = re.search(r'(\d+)', s or '')
    return m.group(1) if m else None

HOW = {'المحافظ': 'GOVERNOR', 'أمين السر': 'SECRETARY', 'المدير': 'DIRECTOR',
       'رئيس الوحدة من موقع البطاقة': 'UNIT_FROM_CARD', 'رئيس الوحدة بالاسم': 'UNIT_BY_NAME',
       'رئيس الوحدة من موقع البطاقة (بلا بطاقة)': 'UNIT_NO_CARD', 'معاون المدير': 'DEPUTY',
       'معاون المدير (بالاسم)': 'DEPUTY_BY_NAME', 'مسمى مطابق': 'TITLE_MATCH',
       'معاون المدير غير محدد ← المدير': 'DEPUTY_UNSPECIFIED', 'تقريبي: أقرب وحدة مذكورة': 'NEAREST_UNIT',
       'مستنتج من الهيكل (لا رئيس في البطاقة)': 'FROM_STRUCTURE',
       'الوحدة الأعلى': 'PLACEHOLDER_UP', 'رأس مديرية': 'PLACEHOLDER_UP'}

def how(h, linked):
    if not linked: return 'UNLINKED'
    if h not in HOW: raise SystemExit(f'unknown link method from build_hierarchy: {h!r} — add it to HOW and 03_lookups.sql')
    return HOW[h]


# ---- units ------------------------------------------------------------------------
disp = {(a, k): v for a, k, v in D['display']}
order = collections.defaultdict(lambda: ['dept', 'sec', 'sub'], D['order'])
arts = [m for m in umap if m['card_key']]                       # every bylaws unit, with or without cards
name_of = {m['card_key']: m['unit_bylaws'] for m in arts}

units = {}        # key tuple -> dict
def add_unit(key, **kw):
    if key not in units: units[key] = {'key': key, 'seq': len(units), **kw}
    return units[key]

add_unit(('GOV',), code='U-GOV', parent=None, type='GOVERNORATE', name='محافظة دمشق', art=None, src='BYLAWS')
add_unit(('16',), code='U-16', parent=('GOV',), type='SECRETARIAT', name='أمانة السر', art='16', src='BYLAWS')
for m in arts:
    a = m['card_key']
    if a == '16.0': continue                                     # أمين السر heads U-16 itself
    add_unit((a,), code=f'U-{a}', parent=('16',) if a.startswith('16.') else ('GOV',), type='DIRECTORATE',
             name=re.sub(r'\s*\(مسودة قرار\)', '', name_of[a]), art=a,
             src='DRAFT_DECISION' if a == '2020' else 'BYLAWS')

def dir_key(a): return ('16',) if a == '16.0' else (a,)

TYPE_WORD = [('قسم', 'QISM'), ('فرع', 'BRANCH'), ('مكتب', 'OFFICE'), ('ورشة', 'WORKSHOP'), ('غرفة', 'ROOM')]
SUB_DEFAULT = {'17': 'QISM', '38': 'BRANCH', '18': 'OFFICE'}
TYPE_AR = {'DEPARTMENT': 'دائرة', 'SECTION': 'شعبة', 'QISM': 'قسم', 'BRANCH': 'فرع', 'OFFICE': 'مكتب',
           'WORKSHOP': 'ورشة', 'ROOM': 'غرفة'}

def unit_type(a, kind, raw):
    if kind == 'dept': return 'DEPARTMENT'
    if kind == 'sec': return 'SECTION'
    w = re.sub(r'^ال', '', (raw or '').split(' ')[0])
    return next((t for word, t in TYPE_WORD if w == word), SUB_DEFAULT.get(a, 'UNIT'))

def unit_name(t, raw):
    """«دائرة التخطيط والاحصاء» whether the card wrote «التخطيط والاحصاء» or «دائرة التخطيط والاحصاء»."""
    raw = re.sub(r'^(ال)?(دائرة|شعبة|قسم|فرع|مكتب|ورشة|غرفة)\s+', '', raw or '').strip()
    return f'{TYPE_AR[t]} {raw}'.strip() if t in TYPE_AR else raw

def ensure_path(a, path):
    """path = (art, l1, l2, l3) positional, as build_hierarchy writes it. Returns the deepest unit key."""
    parent = dir_key(a)
    for i in range(1, len(path)):
        if not path[i]: continue
        key = tuple(path[:i + 1])
        kind = order[a][i - 1]
        raw = disp.get((a, path[i]), path[i])
        t = unit_type(a, kind, raw)
        if key not in units:
            n = sum(1 for u in units.values() if u['parent'] == parent) + 1
            add_unit(key, code=f"{units[parent]['code']}-{n:02d}", parent=parent, type=t,
                     name=unit_name(t, raw), art=a, src='DRAFT_DECISION' if a == '2020' else 'CARDS')
        parent = key
    return parent

def card_path(c):
    return [c['art']] + [c['lv'][k] for k in order[c['art']]]

for c in D['cards']: ensure_path(c['art'], card_path(c))
for v in D['placeholders']: ensure_path(v['art'], v['unit'])


# ---- positions ----------------------------------------------------------------------
pos = {}            # build_hierarchy id -> position dict
seq = collections.Counter()
head_taken = set()
DEP = re.compile(r'معاون\s*(ال)?(مدير|قائد)')

pos['GOV'] = {'code': 'P-GOV', 'unit': ('GOV',), 'card': None, 'title': 'المحافظ', 'heads': 'Y',
              'dep': 'N', 'ph': 'N', 'link': 'TOP', 'parent': None, 'src': 'BYLAWS', 'sort': 0}
head_taken.add(('GOV',))

def deepest(path):
    a = path[0]; k = dir_key(a)
    for i in range(1, len(path)):
        if path[i]: k = tuple(path[:i + 1])
    return k

for c in D['cards']:
    a = c['art']; seq[a] += 1
    if c['heads'] == 'dir':   u = dir_key(a)
    elif c['heads'] and c['heads'] != 'deputy': u = deepest(c['unit']) if c['unit'] else deepest(card_path(c))
    else:                     u = deepest(card_path(c))
    is_head = bool(c['heads']) and c['heads'] != 'deputy' and u not in head_taken
    if is_head: head_taken.add(u)
    pos[c['id']] = {'code': f'P-{a}-{seq[a]:03d}', 'card': f'JD-{a}-{seq[a]:03d}', 'unit': u, 'title': c['title'],
                    'heads': 'Y' if is_head else 'N', 'dep': 'Y' if DEP.match(c['title'] or '') else 'N',
                    'ph': 'N', 'link': how(c['how'], c['parent'] is not None), 'parent': c['parent'],
                    'src': 'DRAFT_DECISION' if a == '2020' else 'CARDS', 'sort': seq[a], 'c': c}

xseq = collections.Counter()
for v in D['placeholders']:
    a = v['art']; xseq[a] += 1
    u = deepest(v['unit']) if len(v['unit']) > 1 else dir_key(a)
    head_taken.add(u)
    pos[v['id']] = {'code': f'P-{a}-X{xseq[a]:02d}', 'card': None, 'unit': u,
                    'title': re.sub(r'\s*\(لا توجد بطاقة\)', '', v['title']), 'heads': 'Y', 'dep': 'N', 'ph': 'Y',
                    'link': how(v['how'], True), 'parent': v['parent'], 'src': 'CARDS', 'sort': 900 + xseq[a]}

# A card nobody could place still has to sit somewhere for the chart to have one
# root. It goes under the head of its directorate with link UNLINKED (confidence
# NONE), which puts it at the top of the review queue rather than hiding it.
dir_head = {p['unit']: pid for pid, p in pos.items() if p['heads'] == 'Y' and len(p['unit']) == 1}
for pid, p in pos.items():
    if pid != 'GOV' and p['parent'] is None:
        d = dir_key(p['c']['art']) if 'c' in p else p['unit'][:1]
        p['parent'] = dir_head.get(d, 'GOV') if dir_head.get(d) != pid else 'GOV'

# sanity: every parent exists, one root, no cycles
for pid, p in pos.items():
    assert p['parent'] is None or p['parent'] in pos, (pid, p['parent'])
for pid in pos:
    seen, x = set(), pid
    while x:
        assert x not in seen, f'cycle at {pid}'; seen.add(x); x = pos[x]['parent']
assert sum(1 for p in pos.values() if p['parent'] is None) == 1


# ---- SQL ------------------------------------------------------------------------------
pre = f"""-- run once per batch, before the data files
MERGE INTO dg_batch t USING (SELECT '{batch}' c FROM dual) s ON (t.batch_code = s.c)
WHEN NOT MATCHED THEN INSERT (batch_code, received_on, description, repo_path)
VALUES ('{batch}', DATE '{batch}',
        'OneDrive_1_10-27-2026: النظام الداخلي المواد 16-46، بطاقات الوصف، توزيع العاملين، مسودة قرار 2020',
        'incoming/{batch}');

-- The AS-IS from the cards is rebuilt from scratch on each load, children first:
-- positions reference units, so a single cascading delete of the scenario could
-- reach the units before the positions. The last DELETE fails if a TO-BE was
-- cloned from this scenario: reloading under a live draft has to be a decision.
DELETE FROM org_position WHERE scenario_id = (SELECT scenario_id FROM org_scenario WHERE scenario_code = '{SCEN}');
DELETE FROM org_unit     WHERE scenario_id = (SELECT scenario_id FROM org_scenario WHERE scenario_code = '{SCEN}');
DELETE FROM org_scenario WHERE scenario_code = '{SCEN}';

INSERT INTO org_scenario (scenario_code, name_ar, name_en, scenario_type, status, legal_basis,
                          effective_from, batch_id, description)
SELECT '{SCEN}', 'الهيكل القائم كما تصفه بطاقات الوصف الوظيفي', 'AS-IS structure as described by the job cards',
       'AS_IS', 'UNDER_REVIEW',
       'القرار 623/ن تاريخ 7/9/2003 المعدل بالقرار 504/ن تاريخ 8/7/2004؛ ومديرية إعادة الإعمار بمسودة قرار غير صادر',
       DATE '2004-07-08', batch_id,
       'مبني آلياً من {len(D["cards"])} بطاقة: موقع الوظيفة والرئيس المباشر. الروابط غير المؤكدة في org_v_review.'
  FROM dg_batch WHERE batch_code = '{batch}';
COMMIT;
"""
(outdir / f'{batch}_00_batch_and_scenario.sql').write_text(pre, encoding='utf-8')

ordered = sorted(units.values(), key=lambda u: (len(u['key']) if u['key'][0] != 'GOV' else 0, u['seq']))
ordered = sorted(ordered, key=lambda u: u['code'].count('-'))       # parents before children
write('01_units', 'units, parents before children', [
    f"INSERT INTO org_unit (scenario_id, unit_code, parent_unit_id, unit_type_code, name_ar, bylaws_article, "
    f"source_type_code, sort_order) VALUES (l_s, {q(u['code'])}, "
    + (f"(SELECT unit_id FROM org_unit WHERE scenario_id = l_s AND unit_code = {q(units[u['parent']]['code'])})"
       if u['parent'] else 'NULL')
    + f", {q(u['type'])}, {q(u['name'])}, {q(u['art'])}, {q(u['src'])}, {u['seq']});"
    for u in ordered])

cards = [p for p in pos.values() if p.get('c')]
write('02_cards', 'job description cards (merge on card_code)', [
    f"MERGE INTO jd_card t USING (SELECT {q(p['card'])} code FROM dual) s ON (t.card_code = s.code)\n"
    f"WHEN MATCHED THEN UPDATE SET t.title_ar = {q(c['title'])}, t.class_code = {q(cls(c['cls']))}, "
    f"t.class_raw = {q(c['cls'])}, t.qual_level_code = {q(qual(c['qual']))}, t.qual_raw = {q(c['qual'])}, "
    f"t.specialisation = {q(c['spec'])}, t.experience_years = {years(c['exp']) or 'NULL'}, "
    f"t.experience_raw = {q(c['exp'])}, t.training = {q(c['train'])}, t.other_knowledge = {q(c['other'])}, "
    f"t.effort_code = {q(effort(c['effort']))}, t.effort_raw = {q(c['effort'])}, t.supervisor_raw = {q(c['boss'])}\n"
    f"WHEN NOT MATCHED THEN INSERT (card_code, batch_id, source_file, source_seq, bylaws_article, title_ar, "
    f"class_code, class_raw, qual_level_code, qual_raw, specialisation, experience_years, experience_raw, "
    f"training, other_knowledge, effort_code, effort_raw, loc_directorate, loc_department, loc_section, "
    f"loc_office, supervisor_raw) VALUES ({q(p['card'])}, l_b, {q(c['file'])}, {c['n']}, {q(c['art'])}, "
    f"{q(c['title'])}, {q(cls(c['cls']))}, {q(c['cls'])}, {q(qual(c['qual']))}, {q(c['qual'])}, "
    f"{q(c['spec'])}, {years(c['exp']) or 'NULL'}, {q(c['exp'])}, {q(c['train'])}, {q(c['other'])}, "
    f"{q(effort(c['effort']))}, {q(c['effort'])}, {q(c['dir'])}, {q(c['dept'])}, {q(c['sec'])}, "
    f"{q(c['sub'])}, {q(c['boss'])});"
    for p in cards for c in [p['c']]])

GENERIC = re.compile(r'(القيام|يقوم)\s*ب?كل\s*ما\s*يكلف|أعمال\s*أخرى\s*مماثلة|اعمال\s*اخرى\s*مماثلة')
tasks = []
for p in cards:
    tasks.append(f"DELETE FROM jd_card_task WHERE card_id = (SELECT card_id FROM jd_card WHERE card_code = {q(p['card'])});")
    for i, t in enumerate(p['c']['tasks'], 1):
        tasks.append(f"INSERT INTO jd_card_task (card_id, seq, task_ar, is_generic) SELECT card_id, {i}, "
                     f"{q(t[:4000])}, '{'Y' if GENERIC.search(t) else 'N'}' FROM jd_card WHERE card_code = {q(p['card'])};")
write('03_tasks', 'card tasks, replaced per card', tasks)

def unit_ref(u): return f"(SELECT unit_id FROM org_unit WHERE scenario_id = l_s AND unit_code = {q(units[u]['code'])})"
write('04_positions', 'positions; supervisors are set in 05', [
    f"INSERT INTO org_position (scenario_id, position_code, unit_id, card_id, title_ar, heads_unit, is_deputy, "
    f"is_placeholder, link_method_code, source_type_code, sort_order) VALUES (l_s, {q(p['code'])}, "
    f"{unit_ref(p['unit'])}, "
    + (f"(SELECT card_id FROM jd_card WHERE card_code = {q(p['card'])})" if p['card'] else 'NULL')
    + f", {q(p['title'])}, '{p['heads']}', '{p['dep']}', '{p['ph']}', {q(p['link'])}, {q(p['src'])}, {p['sort']});"
    for p in pos.values()])

write('05_reporting_lines', 'who reports to whom, by code', [
    f"UPDATE org_position SET reports_to_pos_id = (SELECT position_id FROM org_position WHERE scenario_id = l_s "
    f"AND position_code = {q(pos[p['parent']]['code'])}) WHERE scenario_id = l_s AND position_code = {q(p['code'])};"
    for p in pos.values() if p['parent']])

# staff sheet
ws = openpyxl.load_workbook(staff_xlsx, data_only=True).worksheets[0]
EDU = ['ENG', 'HUMANITIES', 'BASIC_SCI', 'MEDICAL', 'INSTITUTE', 'SECONDARY', 'VOCATIONAL']
row_unit = {}
for m in umap:
    if m['staff_row'] and m['staff_row'] not in row_unit:
        k = m['card_key']
        row_unit[m['staff_row']] = (units[dir_key(k)]['code'] if k and dir_key(k) in units else None, m['match'])
stmts = [f"DELETE FROM dg_staff_count WHERE batch_id = l_b;"]
for r in ws.iter_rows(min_row=4, values_only=True):
    if not r[0]: continue
    label = r[0].strip(); uc, mk = row_unit.get(label, (None, 'staff-only'))
    for e, v in zip(EDU, r[1:8]):
        stmts.append(f"INSERT INTO dg_staff_count (batch_id, row_label, unit_code, match_kind, edu_category, staff) "
                     f"VALUES (l_b, {q(label)}, {q(uc)}, {q(mk)}, '{e}', {int(v or 0)});")
write('06_staff_counts', 'توزيع العاملين.xlsx, one row per unit row and education category', stmts)

conf = collections.Counter(p['link'] for p in pos.values())
print(f"{len(units)} units, {len(pos)} positions ({len(cards)} cards, "
      f"{sum(1 for p in pos.values() if p['ph'] == 'Y')} placeholders), "
      f"{sum(1 for p in pos.values() if p['heads'] == 'Y')} unit heads")
print(dict(conf))
