--------------------------------------------------------------------------------
-- 01_tables.sql — DG schema: organisation structure and job description cards
--
-- Oracle AI Database 26ai, APEX on the same instance. Own schema (DG), own
-- workspace; nothing here refers to any other schema.
--
-- Two halves:
--   ORG_*  the structure. Every row carries SCENARIO_ID, so the structure in
--          the 2003/2004 bylaws, the 2020 draft and any restructuring proposal
--          live side by side. UNIT_CODE / POSITION_CODE are stable across
--          scenarios, which is what lets two scenarios be compared box by box.
--   JD_*   the job description cards (بطاقات الوصف الوظيفي). A card is a
--          document, not part of a scenario: positions in any scenario point
--          at it. A card keeps exactly what the source says (the *_RAW columns)
--          next to the normalised codes, so nothing is lost in cleaning.
--
-- Scenario consistency is enforced by composite foreign keys, not triggers:
-- a parent unit or a supervisor must sit in the same scenario. Triggers that
-- read their own table fail on multi-row inserts; a constraint does not.
--
-- Rerunnable: every CREATE uses IF NOT EXISTS.
--------------------------------------------------------------------------------

---------------------------------------------------------------- lookups -------
CREATE TABLE IF NOT EXISTS org_unit_type (
  unit_type_code  VARCHAR2(30 CHAR)  NOT NULL,
  name_ar         VARCHAR2(100 CHAR) NOT NULL,
  name_en         VARCHAR2(100 CHAR),
  level_hint      NUMBER(2)          NOT NULL,   -- 1 = المحافظة; for colour and sanity checks only
  display_colour  VARCHAR2(20 CHAR),
  sort_order      NUMBER(4),
  CONSTRAINT org_unit_type_pk PRIMARY KEY (unit_type_code)
);

CREATE TABLE IF NOT EXISTS org_source_type (
  source_type_code VARCHAR2(30 CHAR)  NOT NULL,  -- BYLAWS / CARDS / DRAFT_DECISION / MANUAL
  name_ar          VARCHAR2(100 CHAR) NOT NULL,
  name_en          VARCHAR2(100 CHAR),
  CONSTRAINT org_source_type_pk PRIMARY KEY (source_type_code)
);

-- How a position's supervisor was established. CONFIDENCE drives the review queue.
CREATE TABLE IF NOT EXISTS org_link_method (
  link_method_code VARCHAR2(30 CHAR)  NOT NULL,
  name_ar          VARCHAR2(200 CHAR) NOT NULL,
  confidence       VARCHAR2(20 CHAR)  NOT NULL,  -- STATED / APPROXIMATE / INFERRED / NONE
  CONSTRAINT org_link_method_pk PRIMARY KEY (link_method_code),
  CONSTRAINT org_link_method_conf_ck
    CHECK (confidence IN ('STATED','APPROXIMATE','INFERRED','NONE'))
);

CREATE TABLE IF NOT EXISTS jd_class (            -- تصنيف الوظيفة
  class_code  VARCHAR2(30 CHAR)  NOT NULL,
  name_ar     VARCHAR2(100 CHAR) NOT NULL,
  name_en     VARCHAR2(100 CHAR),
  display_colour VARCHAR2(20 CHAR),
  sort_order  NUMBER(4),
  CONSTRAINT jd_class_pk PRIMARY KEY (class_code)
);

CREATE TABLE IF NOT EXISTS jd_qual_level (       -- المؤهل العلمي
  qual_level_code VARCHAR2(30 CHAR)  NOT NULL,
  name_ar         VARCHAR2(100 CHAR) NOT NULL,
  name_en         VARCHAR2(100 CHAR),
  sort_order      NUMBER(4),
  CONSTRAINT jd_qual_level_pk PRIMARY KEY (qual_level_code)
);

CREATE TABLE IF NOT EXISTS jd_effort (           -- نوع الجهد
  effort_code VARCHAR2(30 CHAR)  NOT NULL,
  name_ar     VARCHAR2(100 CHAR) NOT NULL,
  name_en     VARCHAR2(100 CHAR),
  CONSTRAINT jd_effort_pk PRIMARY KEY (effort_code)
);

----------------------------------------------------------- load batches -------
-- One row per delivery from DG. Every loaded row points back to its batch, so
-- "where did this come from" always has an answer.
CREATE TABLE IF NOT EXISTS dg_batch (
  batch_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  batch_code    VARCHAR2(30 CHAR)   NOT NULL,          -- 2026-10-27
  received_on   DATE                NOT NULL,
  description   VARCHAR2(4000 CHAR),
  repo_path     VARCHAR2(400 CHAR),                    -- incoming/2026-10-27
  loaded_on     TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  loaded_by     VARCHAR2(100 CHAR) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
  CONSTRAINT dg_batch_pk PRIMARY KEY (batch_id),
  CONSTRAINT dg_batch_code_uk UNIQUE (batch_code)
);

--------------------------------------------------------------- scenario -------
CREATE TABLE IF NOT EXISTS org_scenario (
  scenario_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  scenario_code   VARCHAR2(30 CHAR)   NOT NULL,
  name_ar         VARCHAR2(200 CHAR)  NOT NULL,
  name_en         VARCHAR2(200 CHAR),
  scenario_type   VARCHAR2(10 CHAR)   NOT NULL,        -- AS_IS / TO_BE
  status          VARCHAR2(20 CHAR)   DEFAULT 'DRAFT' NOT NULL,
  legal_basis     VARCHAR2(400 CHAR),                  -- القرار 623/ن تاريخ 7/9/2003 …
  effective_from  DATE,
  effective_to    DATE,
  cloned_from_id  NUMBER,
  batch_id        NUMBER,
  description     VARCHAR2(4000 CHAR),
  created_by      VARCHAR2(100 CHAR) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
  created_on      TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by      VARCHAR2(100 CHAR),
  updated_on      TIMESTAMP WITH LOCAL TIME ZONE,
  CONSTRAINT org_scenario_pk      PRIMARY KEY (scenario_id),
  CONSTRAINT org_scenario_code_uk UNIQUE (scenario_code),
  CONSTRAINT org_scenario_type_ck CHECK (scenario_type IN ('AS_IS','TO_BE')),
  CONSTRAINT org_scenario_stat_ck CHECK (status IN ('DRAFT','UNDER_REVIEW','APPROVED','ARCHIVED')),
  CONSTRAINT org_scenario_dates_ck CHECK (effective_to IS NULL OR effective_to > effective_from),
  CONSTRAINT org_scenario_clone_fk FOREIGN KEY (cloned_from_id) REFERENCES org_scenario (scenario_id),
  CONSTRAINT org_scenario_batch_fk FOREIGN KEY (batch_id) REFERENCES dg_batch (batch_id)
);

------------------------------------------------------------------- units ------
CREATE TABLE IF NOT EXISTS org_unit (
  unit_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  scenario_id      NUMBER             NOT NULL,
  unit_code        VARCHAR2(40 CHAR)  NOT NULL,        -- stable across scenarios
  parent_unit_id   NUMBER,
  unit_type_code   VARCHAR2(30 CHAR)  NOT NULL,
  name_ar          VARCHAR2(400 CHAR) NOT NULL,
  name_en          VARCHAR2(400 CHAR),
  bylaws_article   VARCHAR2(20 CHAR),                  -- 18, 16.3, 2020
  legal_basis      VARCHAR2(400 CHAR),
  source_type_code VARCHAR2(30 CHAR)  DEFAULT 'CARDS' NOT NULL,
  source_ref       VARCHAR2(400 CHAR),
  is_active        VARCHAR2(1 CHAR)   DEFAULT 'Y' NOT NULL,
  sort_order       NUMBER(6),
  notes            VARCHAR2(4000 CHAR),
  created_by       VARCHAR2(100 CHAR) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
  created_on       TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by       VARCHAR2(100 CHAR),
  updated_on       TIMESTAMP WITH LOCAL TIME ZONE,
  CONSTRAINT org_unit_pk        PRIMARY KEY (unit_id),
  CONSTRAINT org_unit_code_uk   UNIQUE (scenario_id, unit_code),
  CONSTRAINT org_unit_scen_uk   UNIQUE (scenario_id, unit_id),       -- target of the composite FKs
  CONSTRAINT org_unit_scen_fk   FOREIGN KEY (scenario_id) REFERENCES org_scenario (scenario_id) ON DELETE CASCADE,
  CONSTRAINT org_unit_parent_fk FOREIGN KEY (scenario_id, parent_unit_id)
                                REFERENCES org_unit (scenario_id, unit_id),
  CONSTRAINT org_unit_type_fk   FOREIGN KEY (unit_type_code) REFERENCES org_unit_type (unit_type_code),
  CONSTRAINT org_unit_src_fk    FOREIGN KEY (source_type_code) REFERENCES org_source_type (source_type_code),
  CONSTRAINT org_unit_self_ck   CHECK (parent_unit_id IS NULL OR parent_unit_id <> unit_id),
  CONSTRAINT org_unit_active_ck CHECK (is_active IN ('Y','N'))
);
CREATE INDEX IF NOT EXISTS org_unit_parent_ix ON org_unit (scenario_id, parent_unit_id);

------------------------------------------------------------------ cards -------
CREATE TABLE IF NOT EXISTS jd_card (
  card_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  card_code        VARCHAR2(40 CHAR)   NOT NULL,       -- JD-18-003
  batch_id         NUMBER              NOT NULL,
  source_file      VARCHAR2(400 CHAR)  NOT NULL,       -- as received
  source_seq       NUMBER(4)           NOT NULL,       -- position of the card in that file
  bylaws_article   VARCHAR2(20 CHAR),
  title_ar         VARCHAR2(400 CHAR)  NOT NULL,       -- مسمى الوظيفة
  class_code       VARCHAR2(30 CHAR),
  class_raw        VARCHAR2(200 CHAR),
  qual_level_code  VARCHAR2(30 CHAR),
  qual_raw         VARCHAR2(400 CHAR),                 -- المؤهل العلمي
  specialisation   VARCHAR2(400 CHAR),                 -- الاختصاص
  experience_years NUMBER(3),
  experience_raw   VARCHAR2(400 CHAR),                 -- الخبرة
  training         VARCHAR2(1000 CHAR),                -- التدريب
  other_knowledge  VARCHAR2(1000 CHAR),                -- معارف أخرى
  effort_code      VARCHAR2(30 CHAR),
  effort_raw       VARCHAR2(200 CHAR),                 -- نوع الجهد
  -- the location block exactly as written on the card
  loc_directorate  VARCHAR2(400 CHAR),
  loc_department   VARCHAR2(400 CHAR),
  loc_section      VARCHAR2(400 CHAR),
  loc_office       VARCHAR2(400 CHAR),                 -- قسم / مكتب / فرع
  supervisor_raw   VARCHAR2(400 CHAR),                 -- اسم عمل الرئيس المباشر
  status           VARCHAR2(20 CHAR)   DEFAULT 'IMPORTED' NOT NULL,
  review_note      VARCHAR2(4000 CHAR),
  created_by       VARCHAR2(100 CHAR) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
  created_on       TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by       VARCHAR2(100 CHAR),
  updated_on       TIMESTAMP WITH LOCAL TIME ZONE,
  CONSTRAINT jd_card_pk       PRIMARY KEY (card_id),
  CONSTRAINT jd_card_code_uk  UNIQUE (card_code),
  CONSTRAINT jd_card_src_uk   UNIQUE (batch_id, source_file, source_seq),
  CONSTRAINT jd_card_batch_fk FOREIGN KEY (batch_id) REFERENCES dg_batch (batch_id),
  CONSTRAINT jd_card_class_fk FOREIGN KEY (class_code) REFERENCES jd_class (class_code),
  CONSTRAINT jd_card_qual_fk  FOREIGN KEY (qual_level_code) REFERENCES jd_qual_level (qual_level_code),
  CONSTRAINT jd_card_eff_fk   FOREIGN KEY (effort_code) REFERENCES jd_effort (effort_code),
  CONSTRAINT jd_card_stat_ck  CHECK (status IN ('IMPORTED','UNDER_REVIEW','REVIEWED','APPROVED','RETIRED'))
);

CREATE TABLE IF NOT EXISTS jd_card_task (        -- مهام الوظيفة, in card order
  task_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  card_id     NUMBER              NOT NULL,
  seq         NUMBER(4)           NOT NULL,
  task_ar     VARCHAR2(4000 CHAR) NOT NULL,
  is_generic  VARCHAR2(1 CHAR)    DEFAULT 'N' NOT NULL,  -- «القيام بكل ما يكلف به من أعمال أخرى مماثلة»
  CONSTRAINT jd_card_task_pk     PRIMARY KEY (task_id),
  CONSTRAINT jd_card_task_seq_uk UNIQUE (card_id, seq),
  CONSTRAINT jd_card_task_card_fk FOREIGN KEY (card_id) REFERENCES jd_card (card_id) ON DELETE CASCADE,
  CONSTRAINT jd_card_task_gen_ck CHECK (is_generic IN ('Y','N'))
);

-------------------------------------------------------------- positions -------
CREATE TABLE IF NOT EXISTS org_position (
  position_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  scenario_id       NUMBER             NOT NULL,
  position_code     VARCHAR2(40 CHAR)  NOT NULL,       -- stable across scenarios
  unit_id           NUMBER             NOT NULL,
  card_id           NUMBER,                            -- NULL: no card describes this position
  title_ar          VARCHAR2(400 CHAR) NOT NULL,
  reports_to_pos_id NUMBER,
  heads_unit        VARCHAR2(1 CHAR)   DEFAULT 'N' NOT NULL,  -- the head of UNIT_ID
  is_deputy         VARCHAR2(1 CHAR)   DEFAULT 'N' NOT NULL,
  is_placeholder    VARCHAR2(1 CHAR)   DEFAULT 'N' NOT NULL,  -- referenced by other cards, no card of its own
  link_method_code  VARCHAR2(30 CHAR)  NOT NULL,
  headcount         NUMBER(4),                         -- unknown until DG sends staff by position
  status            VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL,
  sort_order        NUMBER(6),
  source_type_code  VARCHAR2(30 CHAR)  DEFAULT 'CARDS' NOT NULL,
  notes             VARCHAR2(4000 CHAR),
  created_by        VARCHAR2(100 CHAR) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
  created_on        TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by        VARCHAR2(100 CHAR),
  updated_on        TIMESTAMP WITH LOCAL TIME ZONE,
  CONSTRAINT org_position_pk       PRIMARY KEY (position_id),
  CONSTRAINT org_position_code_uk  UNIQUE (scenario_id, position_code),
  CONSTRAINT org_position_scen_uk  UNIQUE (scenario_id, position_id),
  CONSTRAINT org_position_scen_fk  FOREIGN KEY (scenario_id) REFERENCES org_scenario (scenario_id) ON DELETE CASCADE,
  CONSTRAINT org_position_unit_fk  FOREIGN KEY (scenario_id, unit_id) REFERENCES org_unit (scenario_id, unit_id),
  CONSTRAINT org_position_rep_fk   FOREIGN KEY (scenario_id, reports_to_pos_id)
                                   REFERENCES org_position (scenario_id, position_id),
  CONSTRAINT org_position_card_fk  FOREIGN KEY (card_id) REFERENCES jd_card (card_id),
  CONSTRAINT org_position_link_fk  FOREIGN KEY (link_method_code) REFERENCES org_link_method (link_method_code),
  CONSTRAINT org_position_src_fk   FOREIGN KEY (source_type_code) REFERENCES org_source_type (source_type_code),
  CONSTRAINT org_position_self_ck  CHECK (reports_to_pos_id IS NULL OR reports_to_pos_id <> position_id),
  CONSTRAINT org_position_flags_ck CHECK (heads_unit IN ('Y','N') AND is_deputy IN ('Y','N')
                                          AND is_placeholder IN ('Y','N')),
  CONSTRAINT org_position_ph_ck    CHECK (is_placeholder = 'N' OR card_id IS NULL),
  CONSTRAINT org_position_stat_ck  CHECK (status IN ('ACTIVE','VACANT','PLANNED','ABOLISHED'))
);
CREATE INDEX IF NOT EXISTS org_position_unit_ix ON org_position (scenario_id, unit_id);
CREATE INDEX IF NOT EXISTS org_position_rep_ix  ON org_position (scenario_id, reports_to_pos_id);
CREATE INDEX IF NOT EXISTS org_position_card_ix ON org_position (card_id);

------------------------------------------------------- staff distribution -----
-- توزيع العاملين.xlsx: a count by education category, per row of DG's sheet.
-- ROW_LABEL is kept as DG wrote it; UNIT_CODE is the match to a unit, when
-- there is one (some rows have no unit in the bylaws).
CREATE TABLE IF NOT EXISTS dg_staff_count (
  staff_count_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  batch_id       NUMBER             NOT NULL,
  row_label      VARCHAR2(200 CHAR) NOT NULL,
  unit_code      VARCHAR2(40 CHAR),
  match_kind     VARCHAR2(20 CHAR)  NOT NULL,          -- exact / renamed / assumed / staff-only
  edu_category   VARCHAR2(30 CHAR)  NOT NULL,
  staff          NUMBER(6)          NOT NULL,
  CONSTRAINT dg_staff_count_pk  PRIMARY KEY (staff_count_id),
  CONSTRAINT dg_staff_count_uk  UNIQUE (batch_id, row_label, edu_category),
  CONSTRAINT dg_staff_count_bfk FOREIGN KEY (batch_id) REFERENCES dg_batch (batch_id),
  CONSTRAINT dg_staff_count_edu CHECK (edu_category IN
    ('ENG','HUMANITIES','BASIC_SCI','MEDICAL','INSTITUTE','SECONDARY','VOCATIONAL'))
);

------------------------------------------------------------- unit lineage -----
-- Where each unit of a scenario comes from in the scenario it was built from:
-- one row per (unit, source unit). A merge has two rows for one unit; a unit
-- that is new has no source; a source unit that is not placed has no unit.
-- Codes, not ids, so a row survives reloading either scenario. This is what
-- the comparison page reads.
CREATE TABLE IF NOT EXISTS org_unit_lineage (
  lineage_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  scenario_id        NUMBER             NOT NULL,       -- the scenario being described
  unit_code          VARCHAR2(40 CHAR),                 -- NULL: source unit not placed
  source_scenario_id NUMBER             NOT NULL,
  source_unit_code   VARCHAR2(40 CHAR),                 -- NULL: a new unit
  relation           VARCHAR2(20 CHAR)  NOT NULL,
  confidence         VARCHAR2(10 CHAR)  NOT NULL,
  is_open            VARCHAR2(1 CHAR)   DEFAULT 'N' NOT NULL,   -- awaiting a decision from DG
  sector_code        VARCHAR2(40 CHAR),                 -- as given by the source document
  note               VARCHAR2(4000 CHAR),
  CONSTRAINT org_unit_lineage_pk   PRIMARY KEY (lineage_id),
  CONSTRAINT org_unit_lineage_sfk  FOREIGN KEY (scenario_id) REFERENCES org_scenario (scenario_id) ON DELETE CASCADE,
  CONSTRAINT org_unit_lineage_ssfk FOREIGN KEY (source_scenario_id) REFERENCES org_scenario (scenario_id),
  CONSTRAINT org_unit_lineage_rel  CHECK (relation IN ('SAME','RENAMED','MERGED','SPLIT','NEW','ABOLISHED')),
  CONSTRAINT org_unit_lineage_conf CHECK (confidence IN ('HIGH','MEDIUM','LOW')),
  CONSTRAINT org_unit_lineage_open CHECK (is_open IN ('Y','N')),
  CONSTRAINT org_unit_lineage_one  CHECK (unit_code IS NOT NULL OR source_unit_code IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS org_unit_lineage_ix ON org_unit_lineage (scenario_id, unit_code);

